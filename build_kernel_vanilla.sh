#!/bin/bash

# Vanilla kernel build for Exynos 2100 - o1s (Galaxy S21) only
# Builds a mainline-style kernel for o1s device variant only

set -e

export ARCH=arm64
export PLATFORM_VERSION=11
export ANDROID_MAJOR_VERSION=r
export SEC_BUILD_CONF_VENDOR_BUILD_OS=13

# Use cross-compiler from toolchain (set by workflow)
export CROSS_COMPILE=${CROSS_COMPILE:-aarch64-linux-android-}
export CC=${CC:-clang}
export LD=${LD:-ld.lld}
export NM=${NM:-llvm-nm}
export OBJCOPY=${OBJCOPY:-llvm-objcopy}
export OBJDUMP=${OBJDUMP:-llvm-objdump}
export STRIP=${STRIP:-llvm-strip}

# Create config fragment for o1s vanilla kernel
cat > /tmp/o1s_vanilla.config << 'EOF'
# Disable non-Exynos platforms
CONFIG_ARCH_AGILEX=n
CONFIG_ARCH_SUNXI=n
CONFIG_ARCH_ALPINE=n
CONFIG_ARCH_BCM2835=n
CONFIG_ARCH_BCM_IPROC=n
CONFIG_ARCH_BERLIN=n
CONFIG_ARCH_BRCMSTB=n
CONFIG_ARCH_K3=n
CONFIG_ARCH_LAYERSCAPE=n
CONFIG_ARCH_LG1K=n
CONFIG_ARCH_HISI=n
CONFIG_ARCH_MEDIATEK=n
CONFIG_ARCH_MESON=n
CONFIG_ARCH_MVEBU=n
CONFIG_ARCH_MXC=n
CONFIG_ARCH_QCOM=n
CONFIG_ARCH_RENESAS=n
CONFIG_ARCH_ROCKCHIP=n
CONFIG_ARCH_SEATTLE=n
CONFIG_ARCH_STRATIX10=n
CONFIG_ARCH_SYNQUACER=n
CONFIG_ARCH_TEGRA=n
CONFIG_ARCH_SPRD=n
CONFIG_ARCH_THUNDER=n
CONFIG_ARCH_THUNDER2=n
CONFIG_ARCH_UNIPHIER=n
CONFIG_ARCH_VEXPRESS=n
CONFIG_ARCH_XGENE=n
CONFIG_ARCH_ZX=n
CONFIG_ARCH_ZYNQMP=n

# Exynos 2100 specific
CONFIG_SOC_EXYNOS2100=y
CONFIG_EXYNOS_PM_DOMAINS=y
CONFIG_EXYNOS_CPUIDLE=y
CONFIG_EXYNOS_THERMAL=y
CONFIG_EXYNOS_ACME=y
CONFIG_EXYNOS_DSU_FREQ=y
CONFIG_EXYNOS_BUS=y
CONFIG_EXYNOS_PCIE=y
CONFIG_EXYNOS_PCIE_GEN2_S2MPU=y
CONFIG_EXYNOS_IOMMU=y
CONFIG_EXYNOS_ADC=y
CONFIG_SND_SOC_SAMSUNG=y

# Essential kernel features
CONFIG_IKCONFIG=y
CONFIG_IKCONFIG_PROC=y
CONFIG_LOG_BUF_SHIFT=21
CONFIG_MODULES=y
CONFIG_MODULE_UNLOAD=y
CONFIG_MODVERSIONS=y
CONFIG_BPF=y
CONFIG_BPF_SYSCALL=y
CONFIG_BPF_JIT=y
CONFIG_NET=y
CONFIG_INET=y
CONFIG_IPV6=y
CONFIG_NETFILTER=y
CONFIG_NF_CONNTRACK=y
CONFIG_NF_NAT=y

# Storage (UFS for o1s)
CONFIG_SCSI=y
CONFIG_BLK_DEV_SD=y
CONFIG_SCSI_UFSHCD=y
CONFIG_SCSI_UFSHCD_PLATFORM=y
CONFIG_SCSI_UFS_DWC_TC_PLATFORM=y
CONFIG_SCSI_UFS_EXYNOS=y
CONFIG_DM_CRYPT=y
CONFIG_DM_VERITY=y
CONFIG_DM_VERITY_AVB=y
CONFIG_ZRAM=y

# Filesystems
CONFIG_EXT4_FS=y
CONFIG_F2FS_FS=y
CONFIG_VFAT_FS=y
CONFIG_EXFAT_FS=y

# Crypto
CONFIG_CRYPTO_AES_ARM64=y
CONFIG_CRYPTO_SHA256_ARM64=y
CONFIG_CRYPTO_SHA1_ARM64_CE=y
CONFIG_CRYPTO_SHA2_ARM64_CE=y

# Debug
CONFIG_DEBUG_INFO=y
CONFIG_DEBUG_INFO_REDUCED=n

# o1s device detection
CONFIG_SEC_DETECT=y

# TZDEV required values (avoid interactive prompts)
CONFIG_TZDEV=m
CONFIG_TZDEV_IWI_EVENT=900
CONFIG_TZDEV_IWI_PANIC=901

# Samsung audio DRAM size
CONFIG_SND_SOC_SAMSUNG_ABOX_DRAM_SIZE=0x1000000

# Local version
CONFIG_LOCALVERSION="-vanilla-o1s"
CONFIG_LOCALVERSION_AUTO=y
EOF

# Start from base arm64 defconfig and merge fragment
make ARCH=arm64 defconfig
cat /tmp/o1s_vanilla.config >> .config
make ARCH=arm64 olddefconfig

# Build kernel + o1s DTBOs only
make ARCH=arm64 -j$(nproc) Image.gz
make ARCH=arm64 -j$(nproc) dtbs_install INSTALL_DTBS_PATH=./dtbs_o1s

# Copy o1s DTBOs
mkdir -p artifacts
cp arch/arm64/boot/Image.gz artifacts/
cp arch/arm64/boot/dts/exynos/samsung/o1s/*.dtbo artifacts/ 2>/dev/null || true

echo "Build complete. o1s artifacts:"
ls -la artifacts/